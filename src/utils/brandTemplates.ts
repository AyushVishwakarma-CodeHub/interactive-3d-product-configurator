export function applyTemplateToConfig(current: ProductConfig, template: BrandTemplate): ProductConfig {
  const base = createDefaultConfig();
  return {
    ...current,
    globalColor: template.config.globalColor || base.globalColor,
    useGlobalColor: template.config.useGlobalColor ?? true,
    frameFinish: template.config.frameFinish || current.frameFinish,
    sections: {
      ...current.sections,
      ...template.config.sections,
    },
    updatedAt: new Date().toISOString(),
  };
}

